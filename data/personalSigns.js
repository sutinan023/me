export function getSignAsset(type, exploded = false) {
  const valid = normalizeSignType(type);
  if (valid === "ENFP") return `/signs/enfp${exploded ? "-exploded" : ""}-mapped-v1.png`;
  if (valid === "ENFJ" && exploded) return "/signs/enfj-exploded-mapped-v1.png";
  return valid
    ? `/signs/${valid.toLowerCase()}${exploded ? (valid === "ISFJ" ? "-exploded" : "-exploded-v2") : ""}${valid === "ISFJ" ? "-transparent" : ""}.png`
    : null;
}
