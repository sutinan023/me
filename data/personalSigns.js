export function normalizeSignType(type) {
  return /^[IE][SN][TF][JP]$/.test(type || "") ? type : null;
}
export function getSignParts(type) {
  const valid = normalizeSignType(type);
  return valid
    ? [...valid].map((letter, index) => ({
        letter,
        name: SIGN_DIMENSIONS[index].name,
        ...SIGN_DIMENSIONS[index].values[letter],
        ...getSignComponent(valid, index),
      }))
    : [];
}

