// Contours follow complete components in the exploded artwork. Coordinates
// are percentages from the top left; holes keep nested parts independent.
function component(part, outline, holes = []) {
  const points = outline.map(([x, y]) => [x / 100, y / 100]);
  const xs = points.map(p => p[0]), ys = points.map(p => p[1]);
  return { part, points, holes: holes.map(h => h.map(([x,y]) => [x/100,y/100])),
    b: [Math.min(...xs), 1-Math.max(...ys), Math.max(...xs), 1-Math.min(...ys)],
    dx: 0, dy: 0, z: 0 };
}
function box(part, l, t, r, b) {
  return component(part, [[l,t],[r,t],[r,b],[l,b]]);
}
