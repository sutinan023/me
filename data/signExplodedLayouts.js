export function getSignClip({ points, holes = [], b }) {
  if (!points) return `inset(${(1-b[3])*100}% ${(1-b[2])*100}% ${b[1]*100}% ${b[0]*100}%)`;
  const contour = [...points, points[0]];
  for (const hole of holes) contour.push(hole[0], ...hole, hole[0], points[0]);
  return `polygon(evenodd, ${contour.map(([x,y]) => `${x*100}% ${y*100}%`).join(', ')})`;
}

// An SVG alpha mask subtracts the union of holes even when they extend beyond
// the outer contour. CSS even-odd polygons cannot express that subtraction.
export function getSignMask({ points, holes = [], exclude = [], b }) {
  const outline = points || [[b[0],1-b[3]],[b[2],1-b[3]],[b[2],1-b[1]],[b[0],1-b[1]]];
  const polygon = (p,fill) => `<polygon fill="${fill}" points="${p.map(v=>v.join(',')).join(' ')}"/>`;
  const mask = (id, content) => `<mask id="${id}" maskUnits="userSpaceOnUse" x="0" y="0" width="1" height="1" style="mask-type:luminance">${content}</mask>`;
  const excludedMasks = exclude.map((r,i)=>mask(`exclude${i}`,
    polygon(r.points,'white')+(r.holes||[]).map(h=>polygon(h,'black')).join(''))).join('');
  const cut = mask('cut', polygon(outline,'white')+holes.map(h=>polygon(h,'black')).join('')+
    exclude.map((_,i)=>`<rect width="1" height="1" fill="black" mask="url(#exclude${i})"/>`).join(''));
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1 1"><defs>${excludedMasks}${cut}</defs><rect width="1" height="1" fill="white" mask="url(#cut)"/></svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}

